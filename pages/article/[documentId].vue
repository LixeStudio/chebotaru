<template>
  <div v-if="article" class="article-page">
    <Header />
    <main class="main">
      <PreviewSection :article="article" :paragraphs="paragraphs" />
      <BodySection :body="article.body" />
      <relatedSection :related-articles="relatedArticles || []" />
      <ContactUs />
    </main>
    <Footer />
  </div>
</template>

<script setup>
import Header from "@/layouts/Header.vue";
import PreviewSection from "@/components/pages/article/previewSection.vue";
import BodySection from "@/components/pages/article/bodySection.vue";
import relatedSection from "@/components/pages/article/relatedSection.vue";
import { usePageSeo } from "@/composables/usePageSeo";
import {
  useJsonLd,
  useBreadcrumbs,
  ARTIST_SAME_AS,
} from "@/composables/useJsonLd";
import { seoDescription, seoTitle } from "@/composables/seoText";
import {
  fetchArticlesByDocumentId,
  fetchRelatedArticles,
} from "@/composables/api/articles";
import {
  availableLocale,
  localizedRouteParams,
} from "@/composables/api/cms";
const ContactUs = defineAsyncComponent(() =>
  import("@/layouts/Contact-us.vue")
);
const Footer = defineAsyncComponent(() => import("@/layouts/Footer.vue"));
const route = useRoute();
const { t, locale } = useI18n();
const localePath = useLocalePath();
// seo: false — hreflang links are generated by usePageSeo from these params
const setI18nParams = useSetI18nParams(false);

const isWhiteTheme = useState("header-white-theme");
isWhiteTheme.value = false;

// the route param is "<documentId>-<slug>", only the documentId identifies the article
const documentId = computed(
  () => String(route.params.documentId || "").split("-")[0]
);

// the article and the related articles only depend on the documentId,
// so both requests run in parallel on the server
const [{ data: result, error }, { data: relatedArticles }] = await Promise.all([
  useAsyncData(
    () => `article-${documentId.value}-${locale.value}`,
    () => fetchArticlesByDocumentId(documentId.value, locale.value)
  ),
  useAsyncData(
    () => `article-related-${documentId.value}-${locale.value}`,
    () => fetchRelatedArticles(documentId.value, locale.value),
    { default: () => [] }
  ),
]);

if (error.value) {
  throw createError({
    statusCode: 503,
    statusMessage: "Article is temporarily unavailable",
    fatal: true,
  });
}
// not translated to this language: temporary redirect to a language it is published in
if (result.value?.status === "other_locales") {
  const lang = availableLocale(result.value.slugs);
  await navigateTo(
    localePath(`/article/${documentId.value}-${result.value.slugs[lang]}`, lang),
    { redirectCode: 302, replace: true }
  );
} else if (result.value?.status !== "ok") {
  throw createError({
    statusCode: 404,
    statusMessage: "Article not found",
    fatal: true,
  });
}
const article = computed(() =>
  result.value?.status === "ok" ? result.value.article : null
);

const articlePath = (lang) => {
  if (!article.value) return documentId.value;
  const slug = article.value.localizedSlugs?.[lang] || article.value.slug;
  return `${article.value.documentId}-${slug}`;
};
const canonicalPath = computed(() =>
  localePath(`/article/${articlePath(locale.value)}`)
);

// an outdated or foreign-language slug permanently redirects to the canonical URL
if (article.value && decodeURIComponent(route.path) !== canonicalPath.value) {
  await navigateTo(
    { path: canonicalPath.value, query: route.query },
    { redirectCode: 301, replace: true }
  );
}

// language switcher and hreflang links use the slug of the target language
// (no record while redirecting to another language: navigateTo does not stop setup on the client)
setI18nParams(
  localizedRouteParams(documentId.value, article.value?.localizedSlugs)
);

const paragraphs = computed(() =>
  (article.value?.previewText || "").split("\n").filter((p) => p.trim().length)
);

// 70-160 characters from the preview, then the start of the text (lines repeating the title are skipped)
const description = computed(() =>
  seoDescription(
    [
      article.value?.previewText,
      ...(article.value?.body || [])
        .filter((block) => block.type === "text")
        .map((block) => block.text),
    ],
    {
      exclude: [article.value?.title || ""],
      fallback: t("seo.article.description"),
    }
  )
);

const { url: pageUrl } = usePageSeo({
  // the title with " — blog by …" only when both fit in 60 characters
  title: () =>
    article.value ? seoTitle(article.value.title, t("seo.article.title")) : "",
  description,
  image: () => article.value?.image.src,
  type: "article",
  path: canonicalPath,
  locales: () => Object.keys(article.value?.localizedSlugs || {}),
});
useSeoMeta({
  articlePublishedTime: () => article.value?.publishedAt || undefined,
  articleModifiedTime: () => article.value?.updatedAt || undefined,
  articleAuthor: () => [t("seo.siteName")],
});

// personal blog of the artist: the author and publisher is the site owner, whose page is "About the artist"
const siteUrl = String(
  useRuntimeConfig().public.SITE_URL || "https://andriichebotaru.com"
).replace(/\/+$/, "");
const artist = computed(() => ({
  "@type": "Person",
  name: t("seo.siteName"),
  url: siteUrl + localePath("/about-artist"),
  sameAs: ARTIST_SAME_AS,
}));
useJsonLd("article", () =>
  article.value
    ? {
        "@type": "BlogPosting",
        headline: article.value.title.trim(),
        url: pageUrl.value,
        mainEntityOfPage: pageUrl.value,
        image: article.value.image.src || undefined,
        description: description.value,
        datePublished: article.value.publishedAt || undefined,
        dateModified:
          article.value.updatedAt || article.value.publishedAt || undefined,
        inLanguage: locale.value,
        author: artist.value,
        publisher: artist.value,
      }
    : null
);

useBreadcrumbs(() =>
  article.value
    ? [
        { name: t("seo.siteName"), path: localePath("/") },
        { name: t("footer.links.aboutAuthor.blog"), path: localePath("/blog") },
        { name: article.value.title.trim(), path: canonicalPath.value },
      ]
    : null
);
</script>
