<template>
  <div v-if="picture" class="picture-details-page">
    <Header />
    <main class="main">
      <ArtworkSection :picture="picture" @toggle-popup="togglePopup" />
      <RelatedWorksSection :related-pictures="relatedPictures || []" />
      <ContactUs />
    </main>
    <Footer />
    <PopupComponent
      :is-pop-up-opened="isPopUpOpened"
      @toggle-popup="togglePopup"
    />
  </div>
</template>

<script setup>
import { ref } from "vue";
import Header from "@/layouts/Header.vue";
import ArtworkSection from "@/components/pages/pictureDetails/artworkSection.vue";
import RelatedWorksSection from "@/components/pages/pictureDetails/relatedWorksSection.vue";
import PopupComponent from "@/components/popupComponent.vue";
import { useBodyScrollLock } from "@/composables/useBodyScrollLock";
import { usePageSeo } from "@/composables/usePageSeo";
import { useJsonLd, useBreadcrumbs } from "@/composables/useJsonLd";
import { seoDescription, seoTitle } from "@/composables/seoText";
import {
  fetchPictureByDocumentId,
  fetchRelatedPictures,
} from "@/composables/api/paintings";
import {
  availableLocale,
  localizedRouteParams,
} from "@/composables/api/cms";
const ContactUs = defineAsyncComponent(() =>
  import("@/layouts/Contact-us.vue")
);
const Footer = defineAsyncComponent(() => import("@/layouts/Footer.vue"));
const route = useRoute();
const { t, locale } = useI18n();
const localePath = useLocalePath();
// seo: false — hreflang links are generated by usePageSeo from these params
const setI18nParams = useSetI18nParams(false);

const isWhiteTheme = useState("header-white-theme");
isWhiteTheme.value = false;

const isPopUpOpened = ref(false);

const togglePopup = (actionType = "open") => {
  if (actionType === "open") isPopUpOpened.value = true;
  if (actionType === "close") isPopUpOpened.value = false;
};
useBodyScrollLock(isPopUpOpened);

// the route param is "<documentId>-<slug>", only the documentId identifies the picture
const documentId = computed(
  () => String(route.params.documentId || "").split("-")[0]
);

// loaded on the server so that the artwork, title and meta tags are in the initial HTML. Related works only depend
// on the documentId, so both requests run in parallel; rendering them on the server (not after hydration) keeps the
// section from appearing later and pushing the page down (layout shift)
const [{ data: result, error }, { data: relatedPictures }] = await Promise.all([
  useAsyncData(
    () => `picture-${documentId.value}-${locale.value}`,
    () => fetchPictureByDocumentId(documentId.value, locale.value)
  ),
  useAsyncData(
    () => `picture-related-${documentId.value}-${locale.value}`,
    () => fetchRelatedPictures(documentId.value, locale.value),
    { default: () => [] }
  ),
]);

if (error.value) {
  throw createError({
    statusCode: 503,
    statusMessage: "Picture is temporarily unavailable",
    fatal: true,
  });
}
// not translated to this language: temporary redirect to a language it is published in
if (result.value?.status === "other_locales") {
  const lang = availableLocale(result.value.slugs);
  await navigateTo(
    localePath(
      `/picture-details/${documentId.value}-${result.value.slugs[lang]}`,
      lang
    ),
    { redirectCode: 302, replace: true }
  );
} else if (result.value?.status !== "ok") {
  throw createError({
    statusCode: 404,
    statusMessage: "Picture not found",
    fatal: true,
  });
}
const picture = computed(() =>
  result.value?.status === "ok" ? result.value.picture : null
);

const picturePath = (lang) => {
  if (!picture.value) return documentId.value;
  const slug = picture.value.localizedSlugs?.[lang] || picture.value.slug;
  return `${picture.value.documentId}-${slug}`;
};
const canonicalPath = computed(() =>
  localePath(`/picture-details/${picturePath(locale.value)}`)
);

// an outdated or foreign-language slug permanently redirects to the canonical URL
if (picture.value && decodeURIComponent(route.path) !== canonicalPath.value) {
  await navigateTo(
    { path: canonicalPath.value, query: route.query },
    { redirectCode: 301, replace: true }
  );
}

// language switcher and hreflang links use the slug of the target language
// (no record while redirecting to another language: navigateTo does not stop setup on the client)
setI18nParams(
  localizedRouteParams(documentId.value, picture.value?.localizedSlugs)
);

// "oil on canvas, impressionism, 80x90 cm, 2024": the facts shown on the page, as one sentence
const detailsLine = computed(() => {
  const d = picture.value?.details;
  if (!d) return "";
  return [
    d.material,
    d.style,
    d.sizeInSm ? `${d.sizeInSm} ${t("units.centimeters")}` : "",
    d.year,
  ]
    .filter(Boolean)
    .join(", ");
});

const { url: pageUrl } = usePageSeo({
  // the title with " — artwork by …" only when both fit in 60 characters
  title: () =>
    picture.value
      ? seoTitle(picture.value.title, t("seo.pictureDetails.title"))
      : "",
  // 70-160 characters: description, image text, then the facts of the painting
  description: () =>
    seoDescription(
      [
        picture.value?.description,
        picture.value?.image.alt,
        picture.value?.image.caption,
        detailsLine.value,
      ],
      {
        exclude: [picture.value?.title || ""],
        fallback: t("seo.pictureDetails.description"),
      }
    ),
  image: () => picture.value?.image.src,
  path: canonicalPath,
  locales: () => Object.keys(picture.value?.localizedSlugs || {}),
});

// only data shown on the page; the author is not a separate CMS field, so "creator" is omitted
useJsonLd("artwork", () =>
  picture.value
    ? {
        "@type": "VisualArtwork",
        name: picture.value.title.trim(),
        url: pageUrl.value,
        image: picture.value.image.src || undefined,
        description: picture.value.image.alt || undefined,
        artform: "Painting",
        artMedium: picture.value.details.material || undefined,
        dateCreated: picture.value.details.year || undefined,
        offers: picture.value.price
          ? {
              "@type": "Offer",
              price: picture.value.price,
              priceCurrency: picture.value.currency,
              availability:
                picture.value.availability === "sold"
                  ? "https://schema.org/SoldOut"
                  : "https://schema.org/InStock",
            }
          : undefined,
      }
    : null
);

useBreadcrumbs(() =>
  picture.value
    ? [
        { name: t("seo.siteName"), path: localePath("/") },
        {
          name: t("footer.links.aboutAuthor.catalog"),
          path: localePath("/catalog"),
        },
        { name: picture.value.title.trim(), path: canonicalPath.value },
      ]
    : null
);
</script>
